function evidence(
  type: VerificationEvidence["type"],
  label: string,
  fileName: string,
  status: VerificationEvidence["status"] = "pending",
  ageDays = 2,
): VerificationEvidence {
  return {
    id: `ev_${type}_${Math.random().toString(36).slice(2, 8)}`,
    type,
    label,
    fileName,
    fileUrl: null,
    uploadedAt: daysAgo(ageDays),
    status,
    reviewerNotes: status === "approved" ? "Document clear and legible." : status === "rejected" ? "Document expired." : null,
  };
}

function internalNote(authorId: string, authorName: string, message: string, ageDays: number): InternalNote {
  return {
    id: `note_${Math.random().toString(36).slice(2, 8)}`,
    authorId,
    authorName,
    message,
    createdAt: daysAgo(ageDays),
  };
}

