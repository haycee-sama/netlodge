/* ------------------------------------------------------ Convenience selectors */

export function getVerificationCaseById(id: string): VerificationRecord | undefined {
  return verificationRecords.find((v) => v.id === id);
}

export function getVerificationCasesByStatus(status: VerificationStatus): VerificationRecord[] {
  return verificationRecords.filter((v) => v.status === status);
}

export function getVerificationCasesByOfficer(officerId: string): VerificationRecord[] {
  return verificationRecords.filter((v) => v.assignedOfficerId === officerId);
}

export function getEscalatedVerificationCases(): VerificationRecord[] {
  return verificationRecords.filter((v) => v.escalatedTo !== null && v.escalatedTo !== undefined);
}

export function getOverdueVerificationCases(): VerificationRecord[] {
  const nowIso = new Date().toISOString();
  return verificationRecords.filter(
    (v) => v.slaDueAt !== null && v.slaDueAt !== undefined && v.slaDueAt < nowIso && (v.status === "pending" || v.status === "in_review"),
  );
}

export function getSupportTicketById(id: string): SupportTicket | undefined {
  return supportTickets.find((t) => t.id === id);
}

export function getUserById(id: string): User | undefined {
  return users.find((u) => u.id === id);
}

export function getUserByEmail(email: string): User | undefined {
  return users.find((u) => u.email.toLowerCase() === email.toLowerCase());
}

export function getRefundById(id: string): Refund | undefined {
  return refunds.find((r) => r.id === id);
}

export function getReconciliationById(id: string): ReconciliationRecord | undefined {
  return reconciliationRecords.find((r) => r.id === id);
}

export function getDisputeById(id: string): Dispute | undefined {
  return disputes.find((d) => d.id === id);
}
